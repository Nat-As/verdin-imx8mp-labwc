#!/usr/bin/env python3
"""Write a BitBake .inc with the NuGet packages of a restored C# project.

  nuget-inc.py <obj/project.assets.json> <output.inc>

Restore the project first on a machine with network access, for the board's
runtime identifier and with the same .NET SDK as the build, e.g.

  dotnet restore -r linux-arm64 GpuTest/GpuTest.csproj

The .inc adds every package of the restore (the complete dependency closure)
to SRC_URI as a pinned nuget.org download into ${WORKDIR}/nuget-feed, which
the labwc-demo-dotnet class uses as the only (offline) package source. The
checksums are taken from the packages in the restore's NuGet cache.
"""
import hashlib
import json
import os
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    assets_path, out_path = sys.argv[1:]
    with open(assets_path) as f:
        assets = json.load(f)
    folders = list(assets.get("packageFolders", {}))
    project = assets["project"]["restore"]["projectName"]

    lines = [
        f"# NuGet packages of {project} (complete dependency closure), restored offline",
        "# from ${WORKDIR}/nuget-feed by the labwc-demo-dotnet class.",
        f"# Generated by scripts/nuget-inc.py from {os.path.basename(assets_path)}; do not edit.",
        "",
        'SRC_URI += " \\',
    ]
    sums = []
    for key, lib in sorted(assets["libraries"].items(), key=lambda kv: kv[0].lower()):
        if lib.get("type") != "package":
            continue
        pkg_id, version = key.split("/")
        lid, lver = pkg_id.lower(), version.lower()
        nupkg = None
        for folder in folders:
            path = os.path.join(folder, lib["path"], f"{lid}.{lver}.nupkg")
            if os.path.exists(path):
                nupkg = path
                break
        if nupkg is None:
            sys.exit(f"{key}: .nupkg not found in {folders}")
        with open(nupkg, "rb") as f:
            sha = hashlib.sha256(f.read()).hexdigest()
        name = f"{lid}-{lver}".replace(".", "_")
        lines.append(f"    https://api.nuget.org/v3-flatcontainer/{lid}/{lver}/{lid}.{lver}.nupkg"
                     f";unpack=0;subdir=nuget-feed;name={name} \\")
        sums.append(f'SRC_URI[{name}.sha256sum] = "{sha}"')
    lines.append('"')
    lines.append("")
    lines.extend(sums)
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out_path}: {len(sums)} packages")


if __name__ == "__main__":
    main()
